import Foundation

/// Config → SBPL. Order matters: SBPL lets later matching rules override earlier ones, so the
/// layout is base → always-on → learned → hardening → final denies (ADR-003).
public struct ProfileCompiler {
    public static let learnProfile = """
        (version 1)
        ;; Menshen learn mode: allow everything, report every operation to the kernel log.
        (allow default (with report))

        """

    let environment: MenshenEnvironment

    public init(environment: MenshenEnvironment) {
        self.environment = environment
    }

    public func compile(_ config: MenshenConfig, source: String? = nil) -> String {
        var out: [String] = []
        let header = source.map { " from \($0)" } ?? ""
        out.append(";; Generated by menshen \(menshenVersion)\(header). Do not edit: edit the JSON config instead.")
        out.append(";; Target: \(config.target.name) \(config.target.bundleId ?? "") team=\(config.target.teamId ?? "none")")
        out.append("(version 1)")
        out.append("(deny default)")
        out.append("(import \"system.sb\")")
        out.append("")
        out.append(";; --- always on")
        out.append("(allow file-read-metadata)")
        let own = config.target.path == config.target.executable
            ? "(literal \(quote(config.target.executable)))"
            : "(subpath \(quote(config.target.path)))"
        out.append("(allow file-read* file-map-executable \(own))")
        out.append("(allow process-exec* \(own)\(config.logging.exec ? " (with report)" : ""))")
        out.append("(allow signal (target same-sandbox))")
        // launchd and cfprefsd check these in user space, so learning can't see them (ADR-004):
        // the app's own preferences, plus Apple system services and preferences.
        if let domain = config.target.bundleId {
            out.append("(allow user-preference-read user-preference-write (preference-domain \(quote(domain))))")
        }
        out.append("(allow mach-lookup (global-name-prefix \"com.apple.\"))")
        out.append("(allow user-preference-read (preference-domain-prefix \"com.apple.\") (preference-domain \"kCFPreferencesAnyApplication\") (preference-domain \"pbs\"))")
        out.append("")
        out.append(";; --- learned (\(config.rules.count))")
        for rule in config.rules { out.append(render(rule, logging: config.logging)) }
        out.append("")
        out.append(";; --- hardening, after learned rules so it wins (\(config.hardening.count))")
        for rule in config.hardening { out.append(render(rule, logging: config.logging)) }
        out.append("")
        out.append(";; --- always on, last")
        out.append("(deny file-link)")
        out.append("")
        return out.joined(separator: "\n")
    }

    func render(_ rule: Rule, logging: LoggingSettings) -> String {
        var parts = ["(\(rule.action.rawValue)", rule.operations.joined(separator: " ")]
        if let filter = filterText(rule.filter) { parts.append(filter) }
        if rule.action == .allow, let category = rule.category, logging.reports(category) {
            parts.append("(with report)")
        }
        var line = parts.joined(separator: " ") + ")"
        var comment = "  ; \(rule.id)"
        if rule.flagged == true { comment += " FLAGGED" }
        if rule.seen > 0 { comment += " seen=\(rule.seen)" }
        line += comment
        return line
    }

    func filterText(_ filter: Filter) -> String? {
        guard let raw = filter.value else { return nil }
        let value = environment.expand(raw)
        switch filter.kind {
        case .any: return nil
        case .subpath: return "(subpath \(quote(value)))"
        case .literal: return "(literal \(quote(value)))"
        case .globalName: return "(global-name \(quote(value)))"
        case .localName: return "(local-name \(quote(value)))"
        case .remote: return "(remote ip \(quote(value)))"
        case .local: return "(local ip \(quote(value)))"
        case .preferenceDomain: return "(preference-domain \(quote(value)))"
        case .iokitUserClientClass: return "(iokit-user-client-class \(quote(value)))"
        }
    }

    func quote(_ s: String) -> String {
        "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    /// Asks the kernel to load the profile (plus permission to exec /usr/bin/true) and run true.
    /// Returns nil on success, or sandbox-exec's error text.
    public static func validate(_ profileText: String) -> String? {
        let probe = profileText + "\n(allow process-exec* (literal \"/usr/bin/true\"))\n"
        let task = Process()
        task.executableURL = URL(fileURLWithPath: "/usr/bin/sandbox-exec")
        task.arguments = ["-p", probe, "/usr/bin/true"]
        let err = Pipe()
        task.standardError = err
        task.standardOutput = FileHandle.nullDevice
        do { try task.run() } catch { return "can't run sandbox-exec: \(error)" }
        task.waitUntilExit()
        let text = String(decoding: err.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        return task.terminationStatus == 0 ? nil : (text.isEmpty ? "exit \(task.terminationStatus)" : text)
    }
}
